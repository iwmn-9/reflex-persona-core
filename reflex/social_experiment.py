"""Fixed paired ablation of social appraisal in two small executable rule sets.

Both settings receive the same observed response-frequency estimates. Social
appraisal adds recipient valuation, not extra world information or hindsight.
Four NPCs face four scripted counterparts; this is not a human study or a
four-person free-for-all. Outcomes are generated by the stated transitions.
"""
import copy
import json
from pathlib import Path
import numpy as np
from .core import Policy, TRAITS, digest, compile_batch
from .examples import context, action, effect
from .laboratory import PROFILES
from .social import SocialPopulation, SocialBinding, SocialEvent

PLAN=dict(version='social-ablation-v1',domains=['allocation','patrol'],
    schedules=['cooperative','exploitative','change_and_repair','bad_luck'],
    seeds=list(range(8)),turns=36,phase_length=12,
    settings=['prediction_only','prediction_and_appraisal'],
    coefficients=dict(capacity=64,half_life=24,max_social_regret=.15),
    caveat='engineered plausibility probes; not psychological or unseen-game validation')


def contexts(seed,domain,energy,reserve,health,history,tick):
    result=[]
    for i,profile in enumerate(PROFILES):
        p=(sum(history[i][-8:])+1)/(len(history[i][-8:])+2)
        if domain=='allocation':
            aid=[effect(.42,p=p,needs={'belonging':.3},values={'benevolence':.6,'universalism':.4},cost=.06),
                 effect(-.12,p=1-p,needs={'belonging':.3},values={'benevolence':.6,'universalism':.4},cost=.06)]
            own=effect(.45,needs={'safety':.12},values={'power':.3,'achievement':.12},cost=.06)
        else:
            aid=[effect(.55,p=p,needs={'belonging':.3},values={'benevolence':.6,'universalism':.4},cost=.06),
                 effect(-.4,p=1-p,needs={'belonging':.3},values={'benevolence':.6,'universalism':.4},cost=.06)]
            own=effect(.4,needs={'safety':.25},values={'power':.3,'security':.3},cost=.06)
        acts=[action('aid',*aid,legal=bool(energy[i]>=.18)),action('independent',own,legal=bool(energy[i]>=.18)),
            action('recover',effect(.08,needs={'physiology':.35},values={'security':.2},cost=.01)),
            action('retaliate',effect(-.8,values={'power':.4},cost=.15),legal=bool(energy[i]>=.18))]
        acts[0]['target']='counterpart';acts[3]['target']='counterpart'
        for a in acts:a['legal']=bool(a['legal'] and health[i]>0)
        acts.append(action('finished',effect(0),legal=bool(health[i]<=0)))
        deficit={'physiology':max(1-energy[i],1-health[i]/8),
                 'safety':max(0,(2-reserve[i])/2),'belonging':.3,'growth':.2}
        c=context('social-'+domain,acts,needs=deficit,traits=dict(zip(TRAITS,profile['traits'])),values=profile['values'],mode=None)
        c['scope'].update(game=domain,npc=profile['id']);c.update(seed=seed,tick=tick)
        c['facts']={'observed_response_frequency':str(p),'response_observations':str(len(history[i]))}
        result.append(c)
    return result


def run(seed,domain,schedule,enabled,turns=36):
    energy=np.full(4,.8);reserve=np.full(4,3.);health=np.full(4,8.);score=np.zeros(4)
    history=[[] for _ in range(4)];trace=[];rng=np.random.default_rng(seed)
    initial=contexts(seed,domain,energy,reserve,health,history,0)
    pop=SocialPopulation(initial,Policy(principle_priority='finite'))
    binding=[{'aid':SocialBinding('counterpart',1),'retaliate':SocialBinding('counterpart',-1)} for _ in range(4)]
    for tick in range(turns):
        cs=contexts(seed,domain,energy,reserve,health,history,tick);b=compile_batch(cs)
        updates={key:getattr(b,key) for key in ('needs','effects','probability','legal')}
        selected=pop.step(True,bindings=binding if enabled else [{} for _ in range(4)],**updates)
        actions=pop.action_ids(selected)
        cooperate=schedule in ('cooperative','bad_luck') or (schedule=='change_and_repair' and (tick<12 or tick>=24))
        failures=rng.random(4)<(.3 if schedule=='bad_luck' else .05)
        observed=[]
        for i,key in enumerate(actions):
            before=dict(energy=float(energy[i]),reserve=float(reserve[i]),health=float(health[i]),score=float(score[i]))
            if key=='finished':
                observed.append([])
                trace.append(dict(tick=tick,npc=PROFILES[i]['id'],action=key,phase=tick//12,
                    cooperate=cooperate,luck_failure=False,before=before,after=before.copy(),
                    actual_gain=0.,appraisal={},values_unchanged=True,terminal=True))
                continue
            if key=='recover':energy[i]=min(1,energy[i]+.35);gain=.08
            else:
                energy[i]=max(0,energy[i]-.18)
                if key=='aid':
                    gain=(.42 if domain=='allocation' else .55) if cooperate and not failures[i] else (-.12 if domain=='allocation' else -.4)
                    if domain=='allocation':reserve[i]+=gain
                    else:health[i]=min(8,health[i]+(.25 if gain>0 else -.75))
                elif key=='independent':gain=.45 if domain=='allocation' else .4;reserve[i]+=.3
                else:gain=-.8;reserve[i]-=.4;health[i]-=.5
            energy[i]=max(0,energy[i]-.025);reserve[i]=max(0,reserve[i]-.1)
            health[i]=max(0,health[i]-(.15 if reserve[i]<=0 else 0));score[i]+=gain
            history[i].append(int(cooperate and not failures[i]))
            # Cooperation is an observed benefit. Deliberate appropriation of
            # the NPC's assistance is an observed harm; failure has no agency.
            benefit=.8 if cooperate and not failures[i] else -1 if key=='aid' and not cooperate else 0.
            observed.append([SocialEvent('counterpart',f'{tick}-{i}',tick,benefit,agency=not (cooperate and failures[i]))])
            trace.append(dict(tick=tick,npc=PROFILES[i]['id'],action=key,cooperate=cooperate,luck_failure=bool(failures[i]),
                phase=tick//12,before=before,after=dict(energy=float(energy[i]),reserve=float(reserve[i]),health=float(health[i]),score=float(score[i])),
                appraisal=copy.deepcopy(pop.social_audit[i]),actual_gain=gain,
                values_unchanged=pop.social[i].values==initial[i]['values'] and pop.social[i].personality==initial[i]['personality'],terminal=bool(health[i]<=0)))
        pop.observe_batch(observed)
    actors=[]
    for i,profile in enumerate(PROFILES):
        rows=[r for r in trace if r['npc']==profile['id']]
        actors.append(dict(npc=profile['id'],score=float(score[i]),health=float(health[i]),reserve=float(reserve[i]),
            aid_by_phase=[sum(r['action']=='aid' for r in rows if r['phase']==phase) for phase in range(3)],
            aid_to_exploiter=sum(r['action']=='aid' and not r['cooperate'] for r in rows),
            retaliation=sum(r['action']=='retaliate' for r in rows),alive=bool(health[i]>0),
            final_relation=pop.social[i].status('counterpart',turns)))
    return dict(domain=domain,schedule=schedule,seed=seed,appraisal=enabled,actors=actors),trace


def experiment(output):
    root=Path(output);root.mkdir(parents=True,exist_ok=True)
    registration=dict(PLAN,source_hashes={str(p.relative_to(Path(__file__).parent)):digest(p.read_text(encoding='utf-8'))
        for p in (Path(__file__),Path(__file__).with_name('social.py'),Path(__file__).with_name('core.py'),Path(__file__).with_name('runtime.py'))})
    frozen=root/'preregister.json'
    if frozen.exists():raise FileExistsError('use a fresh output; do not overwrite a registered comparison')
    frozen.write_text(json.dumps(registration,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    runs=[];checks=dict(decisions=0,personality_value_changes=0,retaliations=0)
    trace_path=root/'trajectories.jsonl'
    with trace_path.open('w',encoding='utf-8') as f:
        for domain in PLAN['domains']:
            for schedule in PLAN['schedules']:
                for seed in PLAN['seeds']:
                    for enabled in (False,True):
                        r,trace=run(seed,domain,schedule,enabled);runs.append(r)
                        checks['decisions']+=sum(t['action']!='finished' for t in trace);checks['personality_value_changes']+=sum(not t['values_unchanged'] for t in trace)
                        checks['retaliations']+=sum(t['action']=='retaliate' for t in trace)
                        f.write(json.dumps(dict(run=r,trace=trace),ensure_ascii=False)+'\n')
    result=dict(plan=registration,runs=runs,checks=checks,episodes=len(runs)*4,
                trajectory_sha256=__import__('hashlib').sha256(trace_path.read_bytes()).hexdigest(),human_data=False)
    (root/'evaluation.json').write_text(json.dumps(result,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    return result


if __name__=='__main__':
    import argparse
    p=argparse.ArgumentParser();p.add_argument('--output',required=True);args=p.parse_args()
    print(json.dumps({k:v for k,v in experiment(args.output).items() if k not in ('runs','plan')},ensure_ascii=False))
